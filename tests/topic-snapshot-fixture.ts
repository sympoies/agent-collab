// A synthetic demo repository in the topic layout, run through the snapshot script's own rules
// (scripts/demo-snapshot-rules.mjs) so tests and the browser check read what the script produces.

import { assembleSnapshot, type TreeEntry } from "../scripts/demo-snapshot-rules.mjs";
import { parseDemoSnapshot, type DemoSnapshot } from "../src/settings/demo-snapshot";
import { messageText, pngBytes } from "./support";

export const DIAGRAM = pngBytes(4, 4);
export const MARKER =
  "collab-protocol: 1\ninbox-layout: topic\nparticipants: alice-agent, bob-agent\n";

const ROOT_INDEX = [
  "<!-- generated by tools/collab.py index; do not edit by hand -->",
  "# Topics",
  "",
  "| topic | title | status |",
  "|---|---|---|",
  "| api | Recipe API | open |",
  "| general | General | open |",
  "| onboarding | Onboarding | closed |",
  "| recipe-legacy |  | legacy |",
  "",
].join("\n");

const id = (month: string, day: number, topic: string, minute = 0) =>
  `${month}-${String(day).padStart(2, "0")}T09${String(minute).padStart(2, "0")}-alice-agent-${topic}-01`;

/** 64 api messages over August to October, one legacy api message in the root inbox. */
export const API_IDS = Array.from({ length: 64 }, (_, n) =>
  id(["2026-08", "2026-09", "2026-10"][Math.floor(n / 22)] as string, 1 + (n % 22), "api", n % 60),
);
export const LEGACY_API_ID = id("2026-07", 6, "api");
export const LEGACY_ONLY_ID = id("2026-07", 8, "recipe-legacy");
export const REFERENCING_ID = API_IDS[API_IDS.length - 1] as string;

function repository(): Record<string, string | Uint8Array> {
  const files: Record<string, string | Uint8Array> = {
    ".agent-collab": MARKER,
    "index.md": ROOT_INDEX,
    "README.md": "# not part of the snapshot\n",
    "topics/general/TOPIC.md": "---\ntitle: General\n---\n",
    "topics/api/TOPIC.md": "---\ntitle: Recipe API\n---\n",
    "topics/onboarding/TOPIC.md": "---\ntitle: Onboarding\nstatus: closed\n---\n",
    "topics/api/fields.csv": "id,title\nr-1,Tomato soup\n",
    "topics/api/fields.csv.md": "Synthetic sample rows; may be shared.\n",
    "topics/api/diagram.png": DIAGRAM,
    "topics/api/diagram.png.md": "Synthetic placeholder image; may be shared.\n",
    [`inbox/${LEGACY_API_ID}.md`]: messageText(
      LEGACY_API_ID,
      "alice-agent",
      "api",
      {},
      "Legacy kickoff.",
    ),
    [`inbox/${LEGACY_ONLY_ID}.md`]: messageText(
      LEGACY_ONLY_ID,
      "alice-agent",
      "recipe-legacy",
      {},
      "Only in the legacy inbox.",
    ),
    [`topics/general/inbox/2026-10/${id("2026-10", 3, "general")}.md`]: messageText(
      id("2026-10", 3, "general"),
      "alice-agent",
      "general",
      {},
      "General note.",
    ),
    [`topics/onboarding/inbox/2026-09/${id("2026-09", 5, "onboarding")}.md`]: messageText(
      id("2026-09", 5, "onboarding"),
      "alice-agent",
      "onboarding",
      {},
      "Onboarding note.",
    ),
  };
  for (const messageId of API_IDS) {
    files[`topics/api/inbox/${messageId.slice(0, 7)}/${messageId}.md`] = messageText(
      messageId,
      "alice-agent",
      "api",
      messageId === REFERENCING_ID ? { refs: "topics/api/diagram.png, topics/api/fields.csv" } : {},
      `API message ${messageId.slice(0, 15)}.`,
    );
  }
  return files;
}

/** The snapshot the script would create for the synthetic repository, parsed like the page does. */
export async function topicSnapshot(): Promise<DemoSnapshot> {
  const files = repository();
  const entries: TreeEntry[] = Object.entries(files).map(([path, content]) => ({
    path,
    type: "blob",
    mode: "100644",
    sha: path,
    size: typeof content === "string" ? new TextEncoder().encode(content).length : content.length,
  }));
  const { json } = await assembleSnapshot({
    entries,
    readBytes: (entry) => {
      const content = files[entry.path] as string | Uint8Array;
      return Promise.resolve(
        typeof content === "string" ? new TextEncoder().encode(content) : content,
      );
    },
    revision: "topic-snapshot-tree",
    generatedAt: "2026-11-04T08:00:00.000Z",
  });
  const snapshot = parseDemoSnapshot(json);
  if (snapshot === null) throw new Error("the fixture snapshot does not parse");
  return snapshot;
}
